#!/usr/bin/env python3
"""Generate LEAN_STATUS.md, the Lean status of every labelled statement of the manuscript.

Usage:
  python3 -u paper/lean_status.py --aux <path to paper.aux> [--rows paper/lean_status_rows.tex] [--out LEAN_STATUS.md]

Reads the rows of paper/lean_status_rows.tex (LaTeX table rows with \\ref{label} and \\lean{name}) and the
printed numbers of the labels from a paper.aux produced by compiling paper/paper.tex, and writes a Markdown
table. Exits 1 if a label of the rows file is missing from the .aux file. -h/--help prints this text.
"""
import os
import re
import sys

HEAD = """# Lean status of the labelled statements

Generated by `paper/lean_status.py` from `paper/lean_status_rows.tex`; the numbers are those printed in the
manuscript built from this commit. The appendix "Formalization" of the manuscript says what is checked and in
which reading.

- **L**: the statement is stated by the Lean theorems named in the last column, with the same hypotheses and
  the same form of the conclusion. Where the manuscript names a constant without giving its value, the Lean
  theorem gives a value or asserts existence. Consequences that a statement draws from its main assertion
  ("hence", "consequently", "in particular") are proved in the manuscript.
- **L′**: a Lean theorem covers the statement in a variant; the last column states the difference.
- **P**: proved in the manuscript only.

All Lean names are in the namespace `Qschubert`.
"""


def opt(a, name, default=None):
    return a[a.index(name) + 1] if name in a else default


def main():
    a = sys.argv[1:]
    if "-h" in a or "--help" in a or "--aux" not in a:
        print(__doc__)
        sys.exit(0 if ("-h" in a or "--help" in a) else 1)
    here = os.path.dirname(os.path.abspath(__file__))
    aux = open(opt(a, "--aux"), encoding="latin-1").read()
    rows = open(opt(a, "--rows", os.path.join(here, "lean_status_rows.tex")), encoding="utf-8").read()
    out = opt(a, "--out", os.path.join(os.path.dirname(here), "LEAN_STATUS.md"))
    num = dict(re.findall(r"\\newlabel\{([^}]+)\}\{\{([^}]*)\}", aux))
    missing = []

    def ref(m):
        lab = m.group(1)
        if lab not in num:
            missing.append(lab)
            return "?? (`%s`)" % lab
        return "%s (`%s`)" % (num[lab], lab)

    def tex(s):
        s = re.sub(r"\\ref\{([^}]+)\}", ref, s)
        s = re.sub(r"\\lean\{([^}]+)\}", lambda m: "`%s`" % m.group(1), s)
        s = s.replace("~", " ").replace("L$'$", "L′").replace("\\tfrac12", "1/2")
        s = re.sub(r"\$([^$]*)\$", lambda m: "`%s`" % m.group(1).replace("\\beta", "β").replace("\\tfrac", ""), s)
        return s.strip()

    lines, n = [HEAD], 0
    for raw in rows.splitlines():
        raw = raw.strip()
        if not raw or raw.startswith("%"):
            continue
        raw = re.sub(r"\\\\(\[[^\]]*\])?$", "", raw)
        m = re.match(r"\\multicolumn\{3\}\{@\{\}l\}\{\\emph\{(.*)\}\}$", raw)
        if m:
            lines += ["", "## " + tex(m.group(1)), "", "| Statement | Status | Lean theorem; difference |", "|---|---|---|"]
            continue
        cells = [tex(c) for c in raw.split(" & ")]
        if len(cells) != 3:
            sys.exit("cannot parse row: " + raw)
        lines.append("| %s | %s | %s |" % tuple(cells))
        n += 1
    if missing:
        sys.exit("labels missing from the .aux file: " + ", ".join(sorted(set(missing))))
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d rows" % (out, n))


if __name__ == "__main__":
    main()
